"""Re-measure the deterministic figures, read the recorded ones, and write docs/metrics.json.

This repository splits its figures in two, and the split is the point.

The test suite is deterministic, so its figures are re-measured on every run and a drift
breaks the build. The timings are not. Rerunning a benchmark on a shared machine produces
different numbers, and a checker that re-measured them and demanded they match would fail
at random, which trains everybody to ignore it.

So the timings are read from the recorded run in docs/experiments/ rather than regenerated
here. `make bench` regenerates them deliberately, and the diff then shows exactly which
published figures moved. ADR-003 carries the reasoning.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPERIMENT_DIR = ROOT / "docs" / "experiments"
METRICS_PATH = ROOT / "docs" / "metrics.json"

EXPERIMENTS = ("e1_fixed_cost", "e2_size_crossover", "e3_by_operation", "e4_memory_cliff")
CHECKED_DOCUMENTS = ("README.md", "docs/adr/ADR-005-what-this-cannot-measure.md")
TABLE_ANCHOR = ["| {} |"]

ANCHORS: dict[str, list[str]] = {
    "tests_total": ["{} tests"],
    "coverage_line_pct": ["{} percent line coverage"],
    "uncovered_lines": ["{} uncovered lines", "the {} lines"],
    "spark_floor_seconds": ["under {}s", "floor of {}s"],
    "duckdb_floor_seconds": ["duckdb's floor of {}s", "floor is {}s"],
    "spark_floor_multiple": ["{} times lower", "{} times duckdb"],
    "spark_setup_seconds": ["{}s of that", "jvm costs {}s"],
    "worst_launch_spread_ratio": ["varies by up to {}", "spread of {}"],
    "largest_rows": ["largest size measured, {} rows", "{} rows, "],
    "spark_ratio_at_largest": ["still {} times", "{}x slower"],
    "spark_ratio_at_smallest": ["from {}x", "{} times slower at the smallest"],
    "ratio_improvement": ["closes by {}x", "narrowed {}x"],
    "fitted_exponent": ["exponent of {}", "slope of {}"],
    "extrapolated_crossover_billions": ["near {} billion rows"],
    "e3_n_rows": ["all four at {} rows", "{} rows"],
    "spark_ratio_spread": ["spread of {}x", "varies {}x"],
    "distinct_orderings": ["{} ordering", "in {} order"],
    "duckdb_cap_mb": ["under {} mb", "{} mb cap"],
    "pandas_cap_mb": ["needs {} mb", "{} mb before"],
    "polars_cap_mb": ["polars needs {} mb", "not until {} mb"],
    "spark_peak_rss_mb": ["{} mb, the least", "spark uses {} mb"],
    "cap_workload_rows": ["{} row sort", "sorting {} rows"],
}


def run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, check=False, **kwargs)


def measure_suite(skip_tests: bool) -> dict:
    junit, cov = ROOT / "junit.xml", ROOT / "coverage.json"
    if skip_tests:
        missing = [p.name for p in (junit, cov) if not p.exists()]
        if missing:
            raise SystemExit(f"--skip-tests given but {', '.join(missing)} not found")
    else:
        result = run([sys.executable, "-m", "pytest", f"--junitxml={junit}",
                      "--cov=spark_crossover", "--cov-report=json", "-q"],
                     capture_output=True, text=True)
        if result.returncode != 0:
            print(result.stdout[-4000:], file=sys.stderr)
            raise SystemExit("test suite failed, refusing to publish metrics")
    suite = ET.parse(junit).getroot()
    node = suite if suite.tag == "testsuite" else suite.find("testsuite")
    totals = json.loads(cov.read_text())["totals"]
    return {
        "tests_total": int(node.get("tests", 0)) - int(node.get("skipped", 0)),
        "coverage_line_pct": int(totals["percent_covered"]),
        "uncovered_lines": int(totals["missing_lines"]),
    }


def load_experiments() -> dict[str, dict]:
    payloads = {}
    for name in EXPERIMENTS:
        path = EXPERIMENT_DIR / f"{name}.json"
        if not path.exists():
            raise SystemExit(
                f"recorded experiment missing: {path.name}\n"
                "Timings are not regenerated by this script, because rerunning them "
                "produces different numbers. Run `make bench` to record a fresh run."
            )
        payloads[name] = json.loads(path.read_text())
    return payloads


def derive(suite: dict, exp: dict[str, dict]) -> dict:
    e1, e2 = exp["e1_fixed_cost"], exp["e2_size_crossover"]
    e3, e4 = exp["e3_by_operation"], exp["e4_memory_cliff"]

    metrics: dict = {
        **suite,
        "spark_floor_seconds": round(e1["spark_floor_seconds"], 2),
        "duckdb_floor_seconds": round(e1["duckdb_floor_seconds"], 3),
        "spark_floor_multiple": round(e1["spark_floor_multiple"], 0),
        "spark_setup_seconds": round(e1["spark_setup_seconds"], 2),
        "worst_launch_spread_ratio": round(e1["worst_launch_spread_ratio"], 2),
        "largest_rows": e2["largest_rows"],
        "spark_ratio_at_largest": round(e2["spark_ratio_at_largest"], 1),
        "spark_ratio_at_smallest": round(e2["spark_ratio_at_smallest"], 0),
        "ratio_improvement": round(e2["ratio_improvement"], 1),
        "fitted_exponent": round(e2["fitted_exponent"], 3),
        "extrapolated_crossover_billions": round(
            e2["extrapolated_crossover_rows"] / 1e9, 1),
        "e3_n_rows": e3["n_rows"],
        "spark_ratio_spread": round(e3["spark_ratio_spread"], 1),
        "distinct_orderings": e3["distinct_single_node_orderings"],
        "cap_workload_rows": e4["n_rows"],
        "duckdb_cap_mb": e4["lowest_cap_survived_mb"]["duckdb"],
        "pandas_cap_mb": e4["lowest_cap_survived_mb"]["pandas"],
        "polars_cap_mb": e4["lowest_cap_survived_mb"]["polars"],
    }

    for engine, reading in e4["uncapped"].items():
        metrics[f"{engine}_peak_rss_mb"] = int(reading["peak_rss_mb"])
        ANCHORS.setdefault(f"{engine}_peak_rss_mb", TABLE_ANCHOR)
        metrics[f"e4_{engine}_work"] = round(reading["work_seconds"], 2)
        ANCHORS.setdefault(f"e4_{engine}_work", TABLE_ANCHOR)

    for cell in e1["cells"]:
        key = cell["engine"]
        metrics[f"e1_{key}_setup"] = round(cell["setup_seconds"], 3)
        metrics[f"e1_{key}_floor"] = round(cell["floor_seconds"], 3)
        for suffix in ("setup", "floor"):
            ANCHORS.setdefault(f"e1_{key}_{suffix}", TABLE_ANCHOR)

    for cell in e2["cells"]:
        key = f"{cell['engine']}_{cell['n_rows']}"
        metrics[f"e2_{key}"] = round(cell["work_seconds"], 3)
        ANCHORS.setdefault(f"e2_{key}", TABLE_ANCHOR)

    for size, ratio in e2["spark_ratio_by_size"].items():
        metrics[f"e2_ratio_{size}"] = round(ratio, 1)
        ANCHORS.setdefault(f"e2_ratio_{size}", TABLE_ANCHOR)

    for cell in e3["cells"]:
        key = f"{cell['engine']}_{cell['workload']}"
        metrics[f"e3_{key}"] = round(cell["work_seconds"], 3)
        ANCHORS.setdefault(f"e3_{key}", TABLE_ANCHOR)

    for workload, ratio in e3["spark_ratio_by_workload"].items():
        metrics[f"e3_ratio_{workload}"] = round(ratio, 1)
        ANCHORS.setdefault(f"e3_ratio_{workload}", TABLE_ANCHOR)

    return metrics


def display_strings(metrics: dict) -> dict[str, str]:
    """Formatting declared per metric, because one figure rendering two ways defeats the
    anchor mechanism."""
    row_counts = {"largest_rows", "e3_n_rows", "cap_workload_rows"}
    out = {}
    for key, value in metrics.items():
        if key in row_counts:
            # Thousands separators, so the prose reads as English. The reverse check looks
            # for decimals, and a grouped integer contains none.
            out[key] = f"{value:,}"
        elif key in ("extrapolated_crossover_billions", "ratio_improvement",
                     "spark_ratio_spread", "spark_ratio_at_largest"):
            out[key] = f"{value:.1f}"
        elif isinstance(value, int):
            out[key] = str(value)
        elif key == "fitted_exponent":
            out[key] = f"{value:.3f}"
        elif key.endswith(("_setup", "_floor")) or key.startswith(("e2_", "e3_")):
            out[key] = f"{value:.3f}" if value < 10 else f"{value:.1f}"
        elif key in ("duckdb_floor_seconds",):
            out[key] = f"{value:.3f}"
        else:
            out[key] = f"{value:.2f}" if value < 100 else f"{value:.0f}"
    # Ratios published as whole numbers read as counts otherwise.
    out["spark_floor_multiple"] = f"{metrics['spark_floor_multiple']:.0f}"
    out["spark_ratio_at_smallest"] = f"{metrics['spark_ratio_at_smallest']:.0f}"
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="Re-measure the deterministic figures.")
    parser.add_argument("--skip-tests", action="store_true")
    args = parser.parse_args()
    metrics = derive(measure_suite(args.skip_tests), load_experiments())
    METRICS_PATH.write_text(json.dumps({
        "metrics": metrics, "display": display_strings(metrics), "anchors": ANCHORS,
        "checked_documents": list(CHECKED_DOCUMENTS),
        "note": "suite figures are re-measured here; timings are read from the recorded "
                "run in docs/experiments, because rerunning them changes them",
    }, indent=2) + "\n")
    print(f"wrote {METRICS_PATH} with {len(metrics)} metrics")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
